#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn brief_pinned_mechanisms_resolve() {
        assert_eq!(
            mechanism_name(pkcs11_types::CkMechanismType::AES_GCM.0),
            Some("CKM_AES_GCM")
        );
        assert_eq!(
            mechanism_name(pkcs11_types::CkMechanismType::RSA_PKCS_PSS.0),
            Some("CKM_RSA_PKCS_PSS")
        );
        assert_eq!(
            mechanism_name(pkcs11_types::CkMechanismType::ECDSA.0),
            Some("CKM_ECDSA")
        );
    }

    #[test]
    fn vendor_and_unregistered_ids_have_no_name() {
        assert_eq!(mechanism_name(0x8000_1042), None);
        assert_eq!(mechanism_name(0xFFFF_FFFF), None);
        assert_eq!(mechanism_name(0x0000_FFFF), None);
    }

    #[test]
    fn official_consts_agree_with_the_table() {
        // Spot-check the table against the typed consts (not the
        // comment source): the generator and the consts must agree.
        for (id, name) in [
            (
                pkcs11_types::CkMechanismType::SHA256_RSA_PKCS.0,
                "CKM_SHA256_RSA_PKCS",
            ),
            (pkcs11_types::CkMechanismType::SHA256.0, "CKM_SHA256"),
            (pkcs11_types::CkMechanismType::AES_ECB.0, "CKM_AES_ECB"),
            (
                pkcs11_types::CkMechanismType::EC_KEY_PAIR_GEN.0,
                "CKM_EC_KEY_PAIR_GEN",
            ),
            (
                pkcs11_types::CkMechanismType::GENERIC_SECRET_KEY_GEN.0,
                "CKM_GENERIC_SECRET_KEY_GEN",
            ),
        ] {
            assert_eq!(mechanism_name(id), Some(name), "id 0x{id:x}");
        }
    }
}
